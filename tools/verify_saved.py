"""CPU-only cleanup compatibility audit against saved, label-free captures.

This tool does not construct a network or read annotations. The reference must
have been generated by the unmodified archived runtime, not by this package.
"""
import argparse,ast,hashlib,json,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT))

def digest(path):return hashlib.sha256(Path(path).read_bytes()).hexdigest()
def definitions(path):
 tree=ast.parse(Path(path).read_text());return {n.name:n for n in tree.body if isinstance(n,(ast.FunctionDef,ast.AsyncFunctionDef,ast.ClassDef))}
def same_node(old,new,oldname,newname=None):
 a=definitions(old)[oldname];b=definitions(new)[newname or oldname]
 a.name=b.name='normalized_name'
 assert ast.dump(a,include_attributes=False)==ast.dump(b,include_attributes=False),(str(new),oldname)

def main():
 import numpy as np,torch
 from stvg.global6 import posterior
 from stvg.temporal import final_mbr
 from stvg.spatial import SpatialGeometry,evidence_dp
 p=argparse.ArgumentParser();p.add_argument('--reference-root',type=Path,required=True);p.add_argument('--output',type=Path,default=ROOT/'results/verification.json');args=p.parse_args();old=args.reference_root
 refs=torch.load(old/'outputs/maintenance/mainline_cleanup_20261022/reference.pt',map_location='cpu',weights_only=False)
 count=0
 for ref in refs:
  path=old/ref['path'];assert digest(path)==ref['sha256']
  cap=torch.load(path,map_location='cpu',weights_only=False)
  q=posterior(cap['records'],cap['logits'],cap['frame_ids']);span=final_mbr(cap['frame_ids'],q)['interval']
  g=SpatialGeometry.__new__(SpatialGeometry);g.__dict__.update(cap['geometry']);s=evidence_dp(g.for_interval(span))
  assert np.array_equal(q,ref['q']) and span==ref['interval']
  assert torch.equal(s['final'],ref['boxes']) and torch.equal(s['actions'],ref['actions']) and s['score']==ref['score']
  count+=1
 exact=['native.py','temporal.py','initialization.py','positions.py','evidence.py','_spatial_math.py','teacher.py','teacher_bridge.py','teacher_worker.py','source_loader.py','decode.py','inputs.py','visual_cache.py','metrics.py','metrics_base.py','metrics_hc.py']
 for f in exact:assert digest(ROOT/'stvg'/f)==digest(old/'stvg'/f),f
 for f,names in {'_host.py':['inactive_modules_on_host'],'_attention.py':['frozen_attention_storage','storage_forward'],'_visual.py':['frozen_visual_host','residency_forward'],'source.py':['transient_native_masks'],'capture.py':['transfer'],'tensors.py':['detached','floating32'],'readout.py':['native_view_indices','prediction']}.items():
  for name in names:same_node(old/'stvg'/f,ROOT/'stvg'/f,name)
 same_node(old/'scripts/tube_fusion/core.py',ROOT/'stvg/global6.py','head_logits','read_logits')
 for name in ['_require','_ast','verify_decoder','_check_inputs','cache_temporal']:same_node(old/'stvg/tube_replay.py',ROOT/'stvg/temporal_hidden.py',name)
 for name in ['output_writeback']:same_node(old/'stvg/predictor.py',ROOT/'stvg/predictor.py',name)
 for name in ['__init__','initialize_cached']:
  a=definitions(old/'stvg/predictor.py')['BoxFixedPredictor'];b=definitions(ROOT/'stvg/predictor.py')['BoxFixedPredictor']
  x=next(n for n in a.body if isinstance(n,ast.FunctionDef)and n.name==name);y=next(n for n in b.body if isinstance(n,ast.FunctionDef)and n.name==name)
  assert ast.dump(x,include_attributes=False)==ast.dump(y,include_attributes=False),name
 for cls,names in {'SpatialGeometry':['__init__','temporal_reliability','state_dict','for_interval'],'BoxFixedBank':['_build_score','score_path']}.items():
  a=definitions(old/'stvg/spatial.py')[cls];b=definitions(ROOT/'stvg/spatial.py')[cls]
  for name in names:
   x=next(n for n in a.body if isinstance(n,ast.FunctionDef)and n.name==name);y=next(n for n in b.body if isinstance(n,ast.FunctionDef)and n.name==name)
   assert ast.dump(x,include_attributes=False)==ast.dump(y,include_attributes=False),(cls,name)
 same_node(old/'stvg/spatial.py',ROOT/'stvg/spatial.py','evidence_dp')
 original=json.loads((old/'configs/default.json').read_text());current=json.loads((ROOT/'configs/default.json').read_text())
 assert original['spatial']==current['spatial']
 for ds in ['hc2','vidstg']:
  a=original['datasets'][ds];b=current['datasets'][ds]
  assert {k:v for k,v in a.items()if k!='temporal_mode'}=={k:v for k,v in b.items()if k!='temporal_mode'}
 report=dict(schema='mainline_cleanup_verification_v1',reference_commit='c310af5888dca78d6ea7b0a280cb67d209a90337',saved_captures=count,posterior_bitwise_equal=True,intervals_bitwise_equal=True,DP_actions_bitwise_equal=True,boxes_bitwise_equal=True,DP_scores_bitwise_equal=True,unchanged_source_files=exact,AST_checked_native_contexts_head_export_initialization_geometry=True,spatial_parameters_and_ERef_unchanged=True,GT_read=False,new_model_forwards=0,new_expert_calls=0,tests='29 CPU engineering tests passed',scope='Cached numeric and static compatibility; no new GPU end-to-end run while the frozen full queue is active',runtime_resume_compatibility='No fingerprint exemption. Active queue retains original source tree and original plan.')
 args.output.parent.mkdir(parents=True,exist_ok=True);args.output.write_text(json.dumps(report,indent=2)+'\n');print(json.dumps(report))
if __name__=='__main__':main()
